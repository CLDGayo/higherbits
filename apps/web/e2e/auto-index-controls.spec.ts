test("Google Font choices are fully loaded before the picker opens", async ({ page }, testInfo) => {
  const preview = new ControlsPreview(page)
  await preview.open()
  await preview.group("Appearance")
  const picker = page.getByRole("combobox", { name: "Font family", exact: true })
  await picker.hover()
  await expect(page.getByRole("status").filter({ hasText: "Preparing font previews" })).toBeVisible()
  await expect(page.getByRole("listbox")).toHaveCount(0)
  await picker.click()
  const anton = page.getByRole("option", { name: "Anton", exact: true })
  await expect(anton).toBeVisible()
  await anton.hover()
  const catalog = page.locator('head link[data-hb-google-font-catalog="true"]')
  await expect(catalog).toHaveAttribute("data-hb-google-font-catalog-ready", "true")
  const loadedFamilies = await page.evaluate(() => {
    const loaded: string[] = []
    document.fonts.forEach(face => { if (face.status === "loaded") loaded.push(face.family.replace(/^['"]|['"]$/g, "")) })
    return loaded
  })
  expect(loadedFamilies).toEqual(expect.arrayContaining([...POPULAR_GOOGLE_FONT_FAMILIES]))
  await page.screenshot({ path: testInfo.outputPath("font-family-picker.png") })
  expect(await anton.locator("span.block.truncate").evaluate(element => (element as HTMLElement).style.fontFamily)).toBe("Anton, sans-serif")
  await anton.click()
  await expect(preview.frame.locator('head link[data-hb-google-font="Anton"]')).toHaveCount(1)
  await expectCss(preview.frame.getByRole("heading"), "font-family", "Anton, sans-serif")
  expect(await picker.evaluate(element => (element as HTMLElement).style.fontFamily)).toBe("Anton, sans-serif")
  await picker.click()
  await page.keyboard.press("ArrowDown")
  const sourceCodePro = page.getByRole("option", { name: "Source Code Pro", exact: true })
  await expect(sourceCodePro).toBeFocused()
  await page.keyboard.press("Escape")
  for (const family of ["Poppins", "Source Sans 3", "Exo 2"]) {
    await picker.click()
    await page.getByRole("option", { name: family, exact: true }).click()
    await expect(catalog).toHaveCount(1)
    await expect(preview.frame.locator(`head link[data-hb-google-font="${family}"]`)).toHaveCount(1)
    const cssFamily = /\d/.test(family) ? `"${family}", sans-serif` : `${family}, sans-serif`
    await expectCss(preview.frame.getByRole("heading"), "font-family", cssFamily)
  }
})

