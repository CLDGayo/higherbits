class ControlsPreview {
  readonly frame
  constructor(readonly page: Page) { this.frame = page.frameLocator('iframe[title="Component preview"]') }
  async open() {
    await this.page.goto("/")
    await expect(this.page.getByLabel("Edit part").locator("option").filter({ hasText: "Heading: Original heading" })).toHaveCount(1)
  }
  async part(label: string) { await this.page.getByLabel("Edit part").selectOption({ label }) }
  async group(label: string) {
    const summary = this.page.getByTestId("auto-index-controls").locator("summary").filter({ hasText: new RegExp(`^${label}$`) })
    if (!(await summary.locator("..").getAttribute("open") === "")) await summary.click()
  }
  async fill(label: string, value: string) { await this.page.getByLabel(label, { exact: true }).fill(value) }
  async state() { return JSON.parse(await this.page.getByTestId("control-state").textContent() || "{}") }
  async copy(format: "html" | "react", bundle = "controls-fixture") {
    const response = await this.page.request.post("/export", { data: { format, bundle, controls: await this.state() } })
    expect(response.ok(), await response.text()).toBe(true)
    return (await response.json()).url as string
  }
}

async function expectCss(locator: Locator, property: string, value: string) { await expect(locator).toHaveCSS(property, value) }

