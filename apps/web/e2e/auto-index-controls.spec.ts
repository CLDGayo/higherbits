  await preview.fill("Animation duration", "8")
  await expectCss(preview.frame.locator(".moving"), "animation-duration", "8s")
  await preview.fill("Animation duration", ".5")
  await expect(preview.frame.locator(".moving").evaluate(element => (element as HTMLElement).style.animationDuration)).resolves.toBe("0.5s")
