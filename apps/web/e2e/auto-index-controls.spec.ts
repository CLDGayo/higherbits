test("animation-picker-hover-keyboard-and-reduced-motion previews only the option label", async ({ page }) => {
  const preview = new ControlsPreview(page)
  await preview.open()
  await preview.group("Motion")
  const picker = page.getByRole("combobox", { name: "Animation", exact: true })
  const componentAnimations = () => preview.frame.locator("#root").evaluate(root => root.getAnimations({ subtree: true }).length)
  await picker.click()
  const fade = page.getByRole("option", { name: "Fade Up", exact: true })
  const label = fade.locator("[data-animation-option-label]")
  const before = await componentAnimations()
  await fade.hover()
  await expect.poll(() => label.evaluate(element => element.getAnimations().length)).toBe(1)
  expect(await componentAnimations()).toBe(before)
  expect(await preview.state()).toEqual({})
  await page.mouse.move(0, 0)
  await expect.poll(() => label.evaluate(element => element.getAnimations().length)).toBe(0)
  await page.keyboard.press("Escape")
  await picker.click()
  await page.keyboard.press("ArrowDown")
  const focused = page.getByRole("option", { name: "Fade", exact: true })
  await expect(focused).toBeFocused()
  await expect.poll(() => focused.locator("[data-animation-option-label]").evaluate(element => element.getAnimations().length)).toBe(1)
  await page.keyboard.press("ArrowDown")
  const keyboardSelection = page.getByRole("option", { name: "Fade Up", exact: true })
  await expect(keyboardSelection).toBeFocused()
  await page.keyboard.press("Enter")
  await expect(picker).toContainText("Fade Up")
  await expect.poll(() => componentAnimations()).toBeGreaterThan(before)
  await expect(page.getByTestId("control-state")).toContainText('"animationPreset":"fade-up"')
  await page.emulateMedia({ reducedMotion: "reduce" })
  await expect.poll(() => componentAnimations()).toBe(before)
  await picker.click()
  await page.getByRole("option", { name: "Fade Up", exact: true }).hover()
  await expect.poll(() => page.getByRole("option", { name: "Fade Up", exact: true }).locator("[data-animation-option-label]").evaluate(element => element.getAnimations().length)).toBe(0)
  await page.keyboard.press("Escape")
  await page.emulateMedia({ reducedMotion: "no-preference" })
  await picker.click()
  await page.getByRole("option", { name: "Fade Down", exact: true }).click()
  await expect.poll(() => componentAnimations()).toBeGreaterThan(before)
  await page.emulateMedia({ reducedMotion: "reduce" })
  await expect.poll(() => componentAnimations()).toBe(before)
  await expect(page.getByTestId("control-state")).toContainText('"animationPreset":"fade-down"')
})

